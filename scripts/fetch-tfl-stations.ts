// One-off data refresh: real station coordinates and entrances from TfL's StopPoint API.
// Writes src/station-geo.ts (a TS module, so Vercel's Node ESM runtime can import it). Run: npx tsx scripts/fetch-tfl-stations.ts
import { writeFileSync } from 'node:fs';
import { STATIONS } from '../src/data';

const API = 'https://api.tfl.gov.uk';
const MODES = 'tube,elizabeth-line,overground';

interface Sp { id?: string; naptanId?: string; stopType?: string; lat: number; lon: number; commonName?: string; children?: Sp[]; modes?: string[] }

const pause = (ms: number) => new Promise((r) => setTimeout(r, ms));

// TfL rate-limits anonymous callers: pace requests and back off on 429.
async function get<T>(path: string): Promise<T> {
    for (let attempt = 0; attempt < 6; attempt++) {
        await pause(700);
        const res = await fetch(API + path);
        if (res.status === 429) {
            await pause(5000 * (attempt + 1));
            continue;
        }
        if (!res.ok) throw new Error(`${res.status} ${path}`);
        return res.json() as Promise<T>;
    }
    throw new Error(`rate limited ${path}`);
}

function entrances(sp: Sp, out: { lat: number; lng: number; id: string }[] = []) {
    for (const c of sp.children ?? []) {
        if (/Entrance/.test(c.stopType ?? '')) out.push({ lat: c.lat, lng: c.lon, id: c.naptanId ?? c.id ?? '' });
        entrances(c, out);
    }
    return out;
}

const NAME_OVERRIDE: Record<string, string> = {
    tottenham_court_road: 'Tottenham Court Road',
    shoreditch_high_st: 'Shoreditch High Street',
    clapham_high_st: 'Clapham High Street',
    victoria_stn: 'Victoria',
    kings_cross: "King's Cross St. Pancras",
    highbury_islington: 'Highbury & Islington',
};

const out: Record<string, { lat: number; lng: number; exits: { lat: number; lng: number }[]; naptan: string[] }> = {};
// Entrances for the featured central stations only; elsewhere walks are timed from the station itself.
for (const [id, st] of Object.entries(STATIONS).filter(([, s]) => s.featured)) {
    const q = NAME_OVERRIDE[id] ?? st.name;
    const found = await get<{ matches: { id: string; name: string; lat: number; lon: number }[] }>(
        `/StopPoint/Search/${encodeURIComponent(q)}?modes=${MODES}&maxResults=5`,
    );
    const m = found.matches.find((x) => /station|underground|rail/i.test(x.name) || x.id.startsWith('HUB')) ?? found.matches[0];
    if (!m) throw new Error(`no match for ${id}`);
    const sp = await get<Sp>(`/StopPoint/${m.id}`);
    // A hub contains the Tube/rail stations as children; gather entrances across all of them.
    const ex = entrances(sp);
    const uniq = ex.filter((e, i) => ex.findIndex((f) => Math.abs(f.lat - e.lat) < 1e-5 && Math.abs(f.lng - e.lng) < 1e-5) === i);
    out[id] = {
        lat: Math.round(sp.lat * 1e6) / 1e6,
        lng: Math.round(sp.lon * 1e6) / 1e6,
        exits: uniq.map((e) => ({ lat: Math.round(e.lat * 1e6) / 1e6, lng: Math.round(e.lng * 1e6) / 1e6 })),
        naptan: [m.id],
    };
    console.log(id.padEnd(22), m.id.padEnd(14), m.name.slice(0, 40).padEnd(40), 'exits', uniq.length, 'coord', sp.lat.toFixed(4), sp.lon.toFixed(4), 'was', st.lat, st.lng);
}
const body = Object.entries(out)
    .map(([k, v]) => `    ${k}: { lat: ${v.lat}, lng: ${v.lng}, exits: [${v.exits.map((e) => `{ lat: ${e.lat}, lng: ${e.lng} }`).join(', ')}] },`)
    .join('\n');
writeFileSync(
    'src/station-geo.ts',
    `// Generated by scripts/fetch-tfl-stations.ts from the TfL StopPoint API (station centre + every entrance).\n// Refresh with: npx tsx scripts/fetch-tfl-stations.ts\n\nexport interface Point { lat: number; lng: number }\n\nexport const STATION_GEO: Record<string, { lat: number; lng: number; exits: Point[] }> = {\n${body}\n};\n`,
);
